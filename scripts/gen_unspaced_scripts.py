#!/usr/bin/env python3
"""Write scripts/_unspaced_scripts.py from the Unicode Character Database.

Chinese and Japanese prose puts no spaces between words, so a whitespace
split cannot count its words (#1077). The checkers count each Han,
Hiragana, or Katakana letter or number as one unit instead. Python's unicodedata has
no Script property, so this generator builds the table from three UCD files
of one Unicode version:

  Scripts.txt, ScriptExtensions.txt, extracted/DerivedGeneralCategory.txt

A code point is in the table when its Script_Extensions holds Han, Hiragana,
or Katakana and its General_Category is a letter (L*) or a number (N*).
Script_Extensions covers marks such as the prolonged sound mark U+30FC, whose
Script is Common. Punctuation, symbols, and radicals are left out.

Usage:
  python scripts/gen_unspaced_scripts.py --ucd DIR            # write the table
  python scripts/gen_unspaced_scripts.py --ucd DIR --check    # exit 1 on drift

DIR is the UCD folder from https://www.unicode.org/Public/<version>/ucd/
(DerivedGeneralCategory.txt is read from DIR/extracted/ when it is not in DIR).
"""
from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

OUTPUT = Path(__file__).resolve().parent / "_unspaced_scripts.py"
SOURCE_FILES = ("Scripts.txt", "ScriptExtensions.txt",
                "DerivedGeneralCategory.txt")
# Script_Extensions values use the short aliases; Scripts.txt the long names.
WANTED = {"Han": "Hani", "Hiragana": "Hira", "Katakana": "Kana"}
_HEADER = re.compile(r"^# (?P<name>[A-Za-z]+)-(?P<version>\d+\.\d+\.\d+)\.txt$")


class UcdError(Exception):
    pass


def _records(text: str):
    """Yield (first, last, value) for each data line of a UCD file."""
    for line in text.splitlines():
        data = line.split("#", 1)[0].strip()
        if not data:
            continue
        field, value = (part.strip() for part in data.split(";", 1))
        first, dots, last = field.partition("..")
        if not value:
            raise UcdError(f"no value on line: {line!r}")
        yield int(first, 16), int(last if dots else first, 16), value


def _version(name: str, text: str) -> str:
    match = _HEADER.match(text.splitlines()[0] if text else "")
    if not match or f"{match['name']}.txt" != name:
        raise UcdError(f"{name}: first line is not '# {name[:-4]}-X.Y.Z.txt'")
    return match["version"]


def build(sources: dict[str, str]) -> tuple[str, list[tuple[int, int]]]:
    """The Unicode version and the merged ranges for ``sources``, which maps
    each name in SOURCE_FILES to the file's text."""
    versions = {_version(name, sources[name]) for name in SOURCE_FILES}
    if len(versions) != 1:
        raise UcdError(f"the files are from different versions: {sorted(versions)}")
    wanted_short = set(WANTED.values())
    by_script = {cp for first, last, value in _records(sources["Scripts.txt"])
                 if value in WANTED for cp in range(first, last + 1)}
    # A code point listed in ScriptExtensions.txt takes that list instead.
    by_extension = {
        cp: bool(wanted_short & set(value.split()))
        for first, last, value in _records(sources["ScriptExtensions.txt"])
        for cp in range(first, last + 1)
    }
    points = [
        cp
        for first, last, category in _records(sources["DerivedGeneralCategory.txt"])
        if category.startswith(("L", "N"))
        for cp in range(first, last + 1)
        if by_extension.get(cp, cp in by_script)
    ]
    points = sorted(set(points))
    ranges: list[tuple[int, int]] = []
    for cp in points:
        if ranges and cp == ranges[-1][1] + 1:
            ranges[-1] = (ranges[-1][0], cp)
        else:
            ranges.append((cp, cp))
    return versions.pop(), ranges


def render(version: str, ranges: list[tuple[int, int]],
           digests: dict[str, str]) -> str:
    lines = [
        "# Generated by scripts/gen_unspaced_scripts.py. Do not edit by hand.",
        '"""Code points that the checkers count one by one (#1077).',
        "",
        "Each range holds letters and numbers whose Script_Extensions holds",
        "Han, Hiragana, or Katakana. See gen_unspaced_scripts.py for the rule.",
        '"""',
        "from __future__ import annotations",
        "",
        f'UNICODE_VERSION = "{version}"',
        "SOURCE_SHA256 = {",
    ]
    lines += [f'    "{name}": "{digests[name]}",' for name in SOURCE_FILES]
    lines += ["}", "RANGES: tuple[tuple[int, int], ...] = ("]
    for first, last in ranges:
        lines.append(f"    (0x{first:04X}, 0x{last:04X}),")
    lines += [")", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ucd", type=Path, required=True,
                        help="folder that holds the three UCD files")
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true",
                        help="compare with --output instead of writing it")
    args = parser.parse_args(argv)
    sources, digests = {}, {}
    try:
        for name in SOURCE_FILES:
            path = args.ucd / name
            if not path.exists():
                path = args.ucd / "extracted" / name
            data = path.read_bytes()
            digests[name] = hashlib.sha256(data).hexdigest()
            sources[name] = data.decode("utf-8")
        text = render(*build(sources), digests)
    except (OSError, ValueError, UcdError) as exc:
        print(f"gen_unspaced_scripts: {exc}", file=sys.stderr)
        return 2
    if args.check:
        current = args.output.read_text(encoding="utf-8") if args.output.exists() else ""
        if current != text:
            print(f"gen_unspaced_scripts: {args.output} is out of date", file=sys.stderr)
            return 1
        return 0
    args.output.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
